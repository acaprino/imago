// Builds css/tokens.css from tokens/imago.tokens.json (DTCG 2025.10).
//   node scripts/build-tokens.mjs                 write css/tokens.css
//   node scripts/build-tokens.mjs --check         exit 1 when css/tokens.css is not what the JSON would give
//   --tokens <file> and --css <file> point at other files (the tests build in a temporary folder).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { colorValueToHex } from './color.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LOOKS = ['smooth', 'oni'];
const THEMES = ['dark', 'light'];

const isToken = (node) => node !== null && typeof node === 'object' && '$value' in node;
const entries = (group) => Object.entries(group).filter(([key]) => !key.startsWith('$'));
const alias = (value) => (typeof value === 'string' ? /^\{(.+)\}$/.exec(value)?.[1] : undefined);
const property = (path) => `--im-${path.split('.').at(-1)}`;

function at(tokens, path) {
  const node = path.split('.').reduce((group, key) => group?.[key], tokens);
  if (!isToken(node)) throw new Error(`${path}: no such token`);
  return node;
}

const group = (tokens, path) => {
  const node = path.split('.').reduce((parent, key) => parent?.[key], tokens);
  if (node === undefined || isToken(node)) throw new Error(`${path}: no such group`);
  return node;
};

const family = (name) => (/\s/.test(name) ? `"${name}"` : name);

// One colour: #RRGGBB, rgba() when translucent, transparent when fully so. A mix keeps the accent live in the cascade.
function colour(tokens, path, value, mix) {
  const target = alias(value);
  let css;
  if (target) {
    at(tokens, target);
    css = `var(${property(target)})`;
  } else if (value.colorSpace === 'oklch') {
    const [l, c, h] = value.components;
    css = `oklch(${l} ${c} ${h === 'none' ? 'var(--im-hue)' : h})`;
  } else {
    const hex = colorValueToHex(value);
    const alpha = value.alpha ?? 1;
    css = alpha === 1 ? hex : alpha === 0 ? 'transparent' : `rgba(${[1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ')}, ${alpha})`;
  }
  if (!mix) return css;
  if (!target) throw new Error(`${path}: a mix needs an alias as its value`);
  const other = mix.with === 'transparent' ? 'transparent' : colorValueToHex(mix.with);
  return `color-mix(in srgb, ${css} ${mix.percent}%, ${other})`;
}

// The CSS value of a token; `glass` picks the glass value of a colour that has one.
function render(tokens, path, glass = false) {
  const token = at(tokens, path);
  const { $type: type, $value: value } = token;
  const extension = token.$extensions?.imago ?? {};
  try {
    switch (type) {
      case 'color':
        return colour(tokens, path, glass && extension.glass ? extension.glass : value, extension.mix);
      case 'dimension':
      case 'duration':
        return `${value.value}${value.unit}`;
      case 'cubicBezier':
        return `cubic-bezier(${value.join(', ')})`;
      case 'fontFamily': {
        const target = alias(value);
        return target ? `var(${property(target)})` : value.map(family).join(', ');
      }
      case 'number':
        return value === 0 ? '0' : `${value}${extension.unit ?? ''}`;
      case 'string':
        return value;
      default:
        throw new Error(`unknown $type "${type}"`);
    }
  } catch (error) {
    throw new Error(`${path}: ${error.message}`);
  }
}

function rule(selector, lines, indent = '') {
  return `${indent}${selector} {\n${lines.map((line) => `${indent}  ${line}\n`).join('')}${indent}}\n`;
}

const declarations = (tokens, groupPath, glass = false) =>
  entries(group(tokens, groupPath)).map(([key]) => `${property(key)}: ${render(tokens, `${groupPath}.${key}`, glass)};`);

// Every look and theme must define the same tokens: a missing one would silently fall back to another rule.
function sameKeys(tokens, paths) {
  const [first, ...rest] = paths;
  const expected = entries(group(tokens, first)).map(([key]) => key).sort().join(' ');
  for (const path of rest) {
    const keys = entries(group(tokens, path)).map(([key]) => key).sort().join(' ');
    if (keys !== expected) throw new Error(`${path} does not define the same tokens as ${first}`);
  }
}

function buildCss(tokens) {
  sameKeys(tokens, LOOKS.map((look) => `measure.${look}`));
  sameKeys(tokens, THEMES.map((theme) => `accent.${theme}`));
  sameKeys(tokens, LOOKS.flatMap((look) => THEMES.map((theme) => `look.${look}.${theme}`)));
  const apps = entries(group(tokens, 'app')).map(([app]) => app);
  const hue = (app) => at(tokens, `app.${app}.hue`).$value;
  const out = [];

  out.push('/* Generated by scripts/build-tokens.mjs from tokens/imago.tokens.json. Do not edit: change the JSON, run `npm run tokens`. */\n');

  out.push('/* Fonts, spacing, motion and the widths of the layout: the same in both looks. */');
  out.push(rule('[data-im-look]', declarations(tokens, 'shared')));

  out.push('/* Measures, head font and text style of each look. */');
  for (const look of LOOKS) out.push(rule(`[data-im-look="${look}"]`, declarations(tokens, `measure.${look}`)));

  out.push('/* The hue of each app. */');
  for (const app of apps) out.push(rule(`[data-im-app="${app}"]`, [`--im-hue: ${hue(app)};`]));

  out.push('/* The accent: the hue of the app at the lightness and chroma of the theme. */');
  for (const theme of THEMES) out.push(rule(`[data-im-theme="${theme}"]`, declarations(tokens, `accent.${theme}`)));

  out.push('/* Where oklch() is unknown the accents are the same colours as hex, clipped into sRGB, per app. */');
  const fallback = [];
  for (const app of apps) {
    for (const theme of THEMES) {
      const lines = entries(group(tokens, `accent.${theme}`))
        .filter(([, token]) => token.$value.colorSpace === 'oklch')
        .map(([key, token]) => `${property(key)}: ${colorValueToHex(token.$value, hue(app))};`);
      fallback.push(rule(`[data-im-app="${app}"][data-im-theme="${theme}"]`, lines, '  '));
    }
  }
  out.push(`@supports not (color: oklch(0.5 0.1 100)) {\n${fallback.join('')}}\n`);

  out.push('/* Colours without glass: every surface is opaque. */');
  for (const look of LOOKS) {
    for (const theme of THEMES) out.push(rule(`[data-im-look="${look}"][data-im-theme="${theme}"]`, declarations(tokens, `look.${look}.${theme}`)));
  }

  out.push('/* Colours under .im-glass: the surfaces let the acrylic of the window through. */');
  for (const look of LOOKS) {
    for (const theme of THEMES) out.push(rule(`.im-glass[data-im-look="${look}"][data-im-theme="${theme}"]`, declarations(tokens, `look.${look}.${theme}`, true)));
  }

  return out.join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const option = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
  const tokensFile = option('--tokens') ?? join(root, 'tokens', 'imago.tokens.json');
  const cssFile = option('--css') ?? join(root, 'css', 'tokens.css');
  const name = relative(process.cwd(), cssFile) || cssFile;

  const css = buildCss(JSON.parse(readFileSync(tokensFile, 'utf8')));
  if (args.includes('--check')) {
    const current = existsSync(cssFile) ? readFileSync(cssFile, 'utf8').replace(/\r\n/g, '\n') : undefined;
    if (current !== css) {
      console.error(`${name} is out of date with ${relative(process.cwd(), tokensFile) || tokensFile}: run "npm run tokens".`);
      process.exitCode = 1;
    }
    return;
  }
  mkdirSync(dirname(cssFile), { recursive: true });
  writeFileSync(cssFile, css);
  console.log(`wrote ${name}`);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
