import assert from 'node:assert/strict';

export default async function graph(page) {
  const pane = page.getByRole('region', { name: 'Build dependencies' });
  const section = pane.locator('xpath=ancestor::section[1]');
  const world = pane.locator('.im-graph-world');
  const client = pane.getByRole('button', { name: 'Client', exact: true });
  const service = pane.getByRole('button', { name: 'Service', exact: true });
  await client.locator('.im-row-title').click();
  assert.equal(await client.getAttribute('aria-pressed'), 'true');
  assert.equal(await client.getAttribute('aria-label'), 'Client');
  assert.equal(await client.getAttribute('title'), 'Client <worker>');
  await client.focus();
  await client.press('ArrowRight');
  assert.ok(await service.evaluate(el => el === document.activeElement));
  assert.equal(await pane.locator('.im-graph-node[tabindex="0"]').count(), 1);
  await service.press('Space');
  assert.equal(await service.getAttribute('aria-pressed'), 'true');
  assert.equal(await client.getAttribute('aria-label'), null, 'reusing a node removes an obsolete custom accessible name');
  await service.press('ArrowLeft');
  assert.ok(await client.evaluate(el => el === document.activeElement));
  await pane.getByRole('button', { name: 'Open Store' }).click();
  assert.equal(await section.locator('output').textContent(), 'Opened Store');
  const transform = () => world.evaluate(el => el.style.transform);
  await section.getByRole('button', { name: 'Fit diagram' }).click();
  const initial = await transform();
  await section.getByRole('button', { name: 'Zoom in' }).click();
  assert.notEqual(await transform(), initial);
  await section.getByRole('button', { name: 'Fit diagram' }).click();
  assert.equal(await transform(), initial);
  const box = await pane.boundingBox();
  await page.mouse.move(box.x + 12, box.y + 12);
  await page.mouse.down();
  await page.mouse.move(box.x + 52, box.y + 30, { steps: 4 });
  await page.mouse.up();
  assert.notEqual(await transform(), initial);
  assert.equal(await pane.locator('.im-graph-edge').count(), 3);
  assert.equal(await pane.locator('.im-graph-edge text').textContent(), 'reads');
  const conflict = pane.locator('.im-graph-edge[data-im-tone="err"] path');
  assert.equal(await conflict.getAttribute('marker-end'), null, 'symmetric edges have no directional arrow');
  assert.equal(await conflict.getAttribute('stroke-dasharray'), '1 4');
  await service.click();
  assert.notEqual(await transform(), initial, 'updating a selection preserves the manual camera');
  const layout = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const resize = async width => {
    await page.evaluate(width => window.__imagoGraph.resize(width), width);
    await layout();
  };
  const viewport = () => page.evaluate(() => window.__imagoGraph.viewport());
  const manual = await viewport();
  assert.equal(manual.fitted, false);
  await page.evaluate(() => window.__imagoGraph.remount());
  assert.deepEqual(await viewport(), manual, 'remount restores a manually positioned camera');
  await resize('70%');
  assert.deepEqual(await viewport(), manual, 'a manual camera remains fixed on resize');
  await section.getByRole('button', { name: 'Fit diagram' }).click();
  const automatic = await viewport();
  assert.equal(automatic.fitted, true);
  await page.evaluate(() => window.__imagoGraph.remount());
  assert.equal((await viewport()).fitted, true, 'remount preserves automatic fitting before the first draw');
  await resize('100%');
  assert.notDeepEqual(await viewport(), automatic, 'automatic fitting follows the new viewport dimensions');
  assert.equal((await viewport()).fitted, true);
  await section.getByRole('button', { name: 'Zoom in' }).click();
  assert.equal((await viewport()).fitted, false);
  await page.evaluate(() => { window.__imagoGraph.hidden(true); window.__imagoGraph.fit(); window.__imagoGraph.remount(); });
  assert.equal((await viewport()).fitted, true, 'requesting fit while hidden survives a remount');
  await page.evaluate(() => window.__imagoGraph.hidden(false));
  await layout();
  assert.equal((await viewport()).fitted, true);
}
